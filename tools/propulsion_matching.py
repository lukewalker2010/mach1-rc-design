def critical_pressure_ratio(gamma=GAMMA_DEFAULT):
    """Pt/Pe_sonic for isentropic flow of a perfect gas."""
    _positive(gamma=gamma)
    if gamma <= 1:
        raise ValueError("gamma must exceed 1")
    return ((gamma + 1.0) / 2.0) ** (gamma / (gamma - 1.0))


def _positive(**values):
    for name, value in values.items():
        if not math.isfinite(value) or value <= 0:
            raise ValueError(f"{name} must be finite and positive")


def _nonnegative(**values):
    for name, value in values.items():
        if not math.isfinite(value) or value < 0:
            raise ValueError(f"{name} must be finite and nonnegative")


def _fraction(**values):
    _nonnegative(**values)
    if any(value > 1 for value in values.values()):
        raise ValueError("fractions must be <= 1")


def choked_mass_flow(Pt, Tt, A_eff, gamma=GAMMA_DEFAULT, R=R_DEFAULT):
    """Choked (sonic) throat mass flow, kg/s."""
    _positive(Pt=Pt, Tt=Tt, A_eff=A_eff, R=R)
    critical_pressure_ratio(gamma)
    f = math.sqrt(gamma / R) * ((gamma + 1.0) / 2.0) ** (-(gamma + 1.0) / (2.0 * (gamma - 1.0)))
    return Pt * A_eff / math.sqrt(Tt) * f


def pt_required_for_choked_massflow(mdot, Tt, A_eff, gamma=GAMMA_DEFAULT, R=R_DEFAULT):
    """Total pressure, Pa, needed to pass mdot through area A_eff when choked."""
    _positive(mdot=mdot, Tt=Tt, A_eff=A_eff, R=R)
    critical_pressure_ratio(gamma)
    f = math.sqrt(gamma / R) * ((gamma + 1.0) / 2.0) ** (-(gamma + 1.0) / (2.0 * (gamma - 1.0)))
    return mdot * math.sqrt(Tt) / (A_eff * f)


def throat_sonic_velocity(Tt, gamma=GAMMA_DEFAULT, R=R_DEFAULT):
    """Sonic velocity at the throat of a choked convergent nozzle, m/s."""
    _positive(Tt=Tt, R=R)
    critical_pressure_ratio(gamma)
    Tstar = Tt * 2.0 / (gamma + 1.0)
    return math.sqrt(gamma * R * Tstar), Tstar


def achocked(Tt, gamma=GAMMA_DEFAULT, R=R_DEFAULT):
    return throat_sonic_velocity(Tt, gamma, R)[0]


def nozzle_flow(Pt, Tt, A, Pa, gamma=GAMMA_DEFAULT, R=R_DEFAULT, Cd=1.0, eta=1.0):
    """Ideal-gas convergent nozzle.

    Returns dict(mdot, Ve, Pe, choked, F_momentum, F_pressure, F_gross, note).
    eta is a kinetic-energy efficiency on the exit velocity (Ve,eff = sqrt(eta)*Ve).
    Cd scales the effective throat area for mass flow.
    Momentum thrust uses Cd*A mass flow and the effective exit velocity.
    """
    _positive(Pt=Pt, Tt=Tt, A=A, Pa=Pa, R=R, Cd=Cd, eta=eta)
    _fraction(Cd=Cd, eta=eta)
    if Pt < Pa:
        raise ValueError("Pt < Pa: reverse flow is outside this model")
    crit = critical_pressure_ratio(gamma)
    A_eff = Cd * A
    if Pa <= Pt / crit:
        Pe = Pt / crit
        a_s, Tstar = throat_sonic_velocity(Tt, gamma, R)
        Ve = math.sqrt(eta) * a_s
        mdot = choked_mass_flow(Pt, Tt, A_eff, gamma, R)
        choked = True
    else:
        ratio = Pt / Pa
        M = math.sqrt(2.0 / (gamma - 1.0) * (ratio ** ((gamma - 1.0) / gamma) - 1.0))
        Te = Tt / (1.0 + (gamma - 1.0) / 2.0 * M ** 2)
        ae = math.sqrt(gamma * R * Te)
        Ve = math.sqrt(eta) * M * ae
        rhoe = Pa / (R * Te)
        mdot = Cd * rhoe * M * ae * A
        Pe = Pa
        choked = False
    F_mom = mdot * Ve
    F_p = (Pe - Pa) * A
    return {
        "mdot": mdot, "Ve": Ve, "Pe": Pe, "choked": choked,
        "F_momentum": F_mom, "F_pressure": F_p, "F_gross": F_mom + F_p,
        "A": A, "A_eff": A_eff, "Pa": Pa, "crit_pr": crit,
        "note": "choked" if choked else "unchoked",
    }


def flight_net(res, mdot_air, mdot_core_fuel=0.0, mdot_ab_fuel=0.0, Vinf=VINF_M1):
    """Net flight thrust with separated ram bookkeeping.

    Exit momentum uses the TOTAL mass leaving the aircraft (captured air plus
    onboard core/AB fuel); the pressure term uses the nozzle exit
    area and ambient from ``res``; ram is the incoming-AIR momentum deficit.
    Returns (gross, ram, net, mdot_tot)."""
    _nonnegative(mdot_air=mdot_air, mdot_core_fuel=mdot_core_fuel,
                 mdot_ab_fuel=mdot_ab_fuel, Vinf=Vinf)
    _nonnegative(nozzle_mdot=res["mdot"], Ve=res["Ve"])
    _positive(Pe=res["Pe"], Pa=res["Pa"], A=res["A"])
    mdot_tot = mdot_air + mdot_core_fuel + mdot_ab_fuel
    if not math.isclose(mdot_tot, res["mdot"], rel_tol=1e-8, abs_tol=1e-12):
        raise ValueError("air + core fuel + AB fuel must match nozzle mass flow")
    gross = mdot_tot * res["Ve"] + (res["Pe"] - res["Pa"]) * res["A"]
    return gross, mdot_air * Vinf, gross - mdot_air * Vinf, mdot_tot


def heat_addition(mdot_total, cp, mdot_fuel, LHV, eta, T_up, T_ref=298.15):
    """Approximation: mdot_total is UPSTREAM air+core fuel; AB fuel enters at
    zero sensible enthalpy at T_ref. Constant common cp, no dissociation/loss
    beyond eta. Not an exact reacting-gas temperature prediction."""
    _positive(mdot_total=mdot_total, cp=cp, LHV=LHV, eta=eta, T_up=T_up, T_ref=T_ref)
    _fraction(eta=eta)
    _nonnegative(mdot_fuel=mdot_fuel)
    return T_ref + (mdot_total * cp * (T_up - T_ref) + mdot_fuel * LHV * eta) / ((mdot_total + mdot_fuel) * cp)


def fuel_for_temperature_rise(mdot_total, cp, dT, LHV, eta, T_up=T5_DRY, T_ref=298.15):
    """Inverse of heat_addition on the same upstream mass/enthalpy basis."""
    heat_addition(mdot_total, cp, 0, LHV, eta, T_up, T_ref)
    _nonnegative(dT=dT)
    available = LHV * eta - cp * (T_up + dT - T_ref)
    if available <= 0:
        raise ValueError("target temperature is unreachable on this heat model")
    return mdot_total * cp * dT / available


def liner_wall_balance(hg, Tg, eps_g, hc, Tc, Tsh, eps_c, kw, tw, sigma=SIGMA,
                       lo=None, hi=None, tol=1e-3):
    """Steady 1-D lumped liner: gas side (conv+rad) -> wall conduction ->
    annulus back side (conv+rad to shell). Solves the wall hot-face temperature
    T_wo for ENERGY CONSERVATION (gas-side q == back-side q). Prescribing T_wo
    and hoping q matches is not a solution - this is the equilibrium value.

    Returns dict(T_wo, T_wi, q, q_conv_gas, q_rad_gas, q_conv_back, q_rad_back).
    All h/eps/k are explicit unvalidated parameters.
    """
    _positive(Tg=Tg, Tc=Tc, Tsh=Tsh, kw=kw, tw=tw, sigma=sigma, tol=tol)
    _nonnegative(hg=hg, hc=hc)
    _fraction(eps_g=eps_g, eps_c=eps_c)
    if hg + eps_g == 0 or hc + eps_c == 0:
        raise ValueError("both wall faces require heat transfer")
    # Restrict to this model's hot-gas/cold-reservoir heat-flow direction.
    if Tg < max(Tc, Tsh):
        raise ValueError("gas must be at least as hot as the cooling reservoirs")
    # Find the lower hot-face bound whose conducted cold face is nonnegative.
    lower, upper = min(Tc, Tsh), Tg
    for _ in range(100):
        mid = (lower + upper) / 2
        cold = mid - (hg * (Tg-mid) + eps_g*sigma*(Tg**4-mid**4))*tw/kw
        if cold < min(Tc, Tsh):
            lower = mid
        else:
            upper = mid
    lo = upper if lo is None else lo
    hi = Tg if hi is None else hi
    _positive(lo=lo, hi=hi)
    if lo > hi or lo < upper - 1e-8 or hi > Tg:
        raise ValueError("invalid physical wall bracket")

    def q_gas(Two):
        return hg * (Tg - Two) + eps_g * sigma * (Tg ** 4 - Two ** 4)

    def q_back(Two):
        qi = q_gas(Two)
        Twi = Two - qi * tw / kw
        return hc * (Twi - Tc) + eps_c * sigma * (Twi ** 4 - Tsh ** 4)

    f = lambda Two: q_gas(Two) - q_back(Two)
    if f(lo) * f(hi) > 0:
        return {"converged": False, "note": "no sign change in bracket"}
    for _ in range(200):
        mid = 0.5 * (lo + hi)
        if abs(f(mid)) < tol or (hi - lo) < 1e-6:
            break
        if f(lo) * f(mid) <= 0:
            hi = mid
        else:
            lo = mid
    Two = 0.5 * (lo + hi)
    q = q_gas(Two)
    Twi = Two - q * tw / kw
    return {
        "converged": True, "T_wo": Two, "T_wi": Twi, "q": q,
        "q_conv_gas": hg * (Tg - Two), "q_rad_gas": eps_g * sigma * (Tg ** 4 - Two ** 4),
        "q_conv_back": hc * (Twi - Tc), "q_rad_back": eps_c * sigma * (Twi ** 4 - Tsh ** 4),
    }


def shell_blanket_composite(T_shell, k_b, t_b, h_ext, T_amb, eps_f, sigma=SIGMA):
    """Steady 1-D: blanket conduction from T_shell to composite outer surface,
    then external convection + radiation to ambient. Solves T_composite by
    energy balance (conducted q == rejected q). Banded: returns also the heat
    flux and the residual pass against a 373 K composite-contact limit."""
    _positive(T_shell=T_shell, k_b=k_b, t_b=t_b, T_amb=T_amb, sigma=sigma)
    _nonnegative(h_ext=h_ext)
    _fraction(eps_f=eps_f)
    if T_shell < T_amb:
        raise ValueError("T_shell must be >= ambient for this heating model")
    lo = T_amb
    hi = T_shell

    def q_cond(Tc):
        return (k_b / t_b) * (T_shell - Tc)

    def q_ext(Tc):
        return h_ext * (Tc - T_amb) + eps_f * sigma * (Tc ** 4 - T_amb ** 4)

    f = lambda Tc: q_cond(Tc) - q_ext(Tc)
    if f(lo) * f(hi) > 0:
        return {"converged": False, "note": "no sign change"}
    for _ in range(200):
        mid = 0.5 * (lo + hi)
        if abs(f(mid)) < 1e-2 or (hi - lo) < 1e-5:
            break
        if f(lo) * f(mid) <= 0:
            hi = mid
        else:
            lo = mid
    Tc = 0.5 * (lo + hi)
    q = q_cond(Tc)
    return {
        "converged": True, "T_composite": Tc,
        "q": q, "pass_100C": Tc < 373.15,
        "q_cond": q, "q_ext": q_ext(Tc),
    }


def _fmt_bar(p):
    return p / 1.0e5


