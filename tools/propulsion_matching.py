    print("  at T_c=423 K; the annulus estimate is only h_ann=125 W/m2K.")
    for Tc in (423.0, 516.0):
        r = liner_wall_balance(hg=579.0, Tg=1800.0, eps_g=0.25,
                               hc=125.0, Tc=Tc, Tsh=610.0, eps_c=0.3,
                               kw=18.0, tw=0.001)
