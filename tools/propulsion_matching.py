    q_claimed, T_wo_claimed, T_wi_claimed = 382e3, 1150.0, 1171.0
    Q_claimed = q_claimed * A_liner
    print(f"  coolant Q available (m={m_cool} kg/s, cp={cp_cool}, 423->610 K) = "
          f"{Q_avail:.0f} W vs claimed liner load {Q_claimed:.0f} W "
          f"({'OK' if Q_avail >= Q_claimed else 'DEFICIT'}).")
    print("  -> a consistent T_wo must satisfy BOTH the wall resistance chain AND")
    print("     coolant energy balance; 17's 382 kW/m2 @ T_wo=1150 K is not that state.")

    # --- 7. Shell -> blanket -> composite (R08)
    print("\n[S7] SHELL TO FUSELAGE: 5 mm blanket (k=0.05) with claimed shell 610 K")
    print(f"  {'h_ext':>6} {'eps_f':>6} {'T_composite K':>13} {'q kW/m2':>8} {'<100C?':>7}")
