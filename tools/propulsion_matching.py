#!/usr/bin/env python3
"""
propulsion_matching.py — parametric ideal-gas nozzle + afterburner heat-balance
model for the Mach 1 RC program (25 R07/R08 evidence).

Python stdlib only. No CAD is regenerated by this tool.

WHAT THIS REPLACES
  Docs 18 sec 2.1 / 21 sec 1 & 6 use the momentum-only shortcut
  gross = mdot * Vj,  ram = mdot * Vinf,  net = gross - ram,
  with Vj = Vj_dry*sqrt(T7/1000) and a static-to-flight mass-flow ratio.
  That assumes (a) equal effective exhaust velocity, (b) negligible pressure
  thrust, (c) a single mdot that is both core air and nozzle flow. None of
  (a)-(c) is established; nozzle velocity depends on pressure ratio, throat
  area, discharge coefficient and total temperature, not T7 alone (25 R07).

  This tool replaces the logical equivalence with a parametric ideal-gas
  convergent-nozzle model:
    * choked mass flow:      mdot = Cd Pt A*/sqrt(Tt) * sqrt(g/R) *
                                   ((g+1)/2)^(-(g+1)/(2(g-1)))
    * critical pressure:     Pt/Pe* = ((g+1)/2)^(g/(g-1))
    * throat sonic speed:    a* = sqrt(g R T*), T* = 2 Tt/(g+1)
    * thrust split:          F = mdot Ve + (Pe-Pa) Ae
    * ram bookkeeping:       net = gross - mdot_air * Vinf
                             (fuel carried onboard adds exit momentum without
                             a ram penalty; the incoming-air momentum deficit
                             is the ram term)
    * heat addition:         constant-cp sensible-enthalpy balance including added fuel

  All gas properties, h, emissivities, discharge coefficient and efficiency are
  EXPLICIT unvalidated parameters. Every number printed below is a
  development/parametric estimate, not a measured result. Baseline mdot = 1.10
  kg/s (18 sec 2.1) is used only as a planning target; nozzle Pt/T7 come from an
  engine map that is NOT available, so closure is not claimed.

Authoritative inputs (cited):
  18 sec 2.1 : mdot_air 1.10 kg/s, T5 ~1000 K, Vj_dry ~566 m/s, net dry ~257 N,
               net wet 450-475 N; ram = 1.10*328 = 361 N
  13:65      : Vinf = 328 m/s at 10 kft ISA; 13:84 Pt/P = 1.893; 13:94-96 corr.
  21 sec 2/3 : AB fuel 27.3 g/s at T7=1800 K, cp=1200, LHV=43 MJ/kg, eta=0.90
  14 sec 1/4 : throats 45 mm dry / 55 mm wet; liner 80 mm ID; CAD ab_liner_step
               has 20 x 1 mm film holes at x=10 mm (the 105-115 target is not
               in CAD, 25 R08)
  17 sec 1c  : film-hole choked-flow constant 2.47e-4 kg/s per 1 mm hole
  17 sec 1e  : annulus h = 125 W/m2K, T_cool_in = 423 K, shell ~610 K
"""

